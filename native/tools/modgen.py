#!/usr/bin/env python3
"""The native layout of the game's modules (main, ITCM, DTCM, every overlay).

The build renames each game object's sections to .m_<module>.<section> (objcopy --prefix-alloc-sections). This writes:
  - sections.ld: a GNU ld script INSERTed into the default one, grouping each module's .data, .bss and static
    initializers (.init_array) between __port_<module>_<kind>_start/_end symbols. The initializers do not go into the
    program's .init_array: port/platform/image.c runs them when the module starts, as the DS does;
  - modules.c / modules.h: the table port/platform/image.c reads (module, overlay id, its gap relocations, ranges).

Usage: modgen.py <out dir> <module>...
"""
import sys
from pathlib import Path


def main():
    out = Path(sys.argv[1])
    mods = sys.argv[2:]
    out.mkdir(parents=True, exist_ok=True)
    data, bss, init = [], [], []
    for m in mods:
        data.append(f"    .port_{m}_data : {{ __port_{m}_data_start = .; *(.m_{m}.data .m_{m}.data.*) "
                    f"__port_{m}_data_end = .; }}")
        bss.append(f"    .port_{m}_bss (NOLOAD) : {{ __port_{m}_bss_start = .; *(.m_{m}.bss .m_{m}.bss.* "
                   f".m_{m}.sbss .m_{m}.sbss.*) __port_{m}_bss_end = .; }}")
        init.append(f"    .port_{m}_init : {{ __port_{m}_init_start = .; KEEP(*(SORT_BY_INIT_PRIORITY(.m_{m}.init_array.*))) "
                    f"KEEP(*(.m_{m}.init_array)) __port_{m}_init_end = .; }}")
    ld = ["/* Generated by tools/modgen.py: the game's modules, grouped for port/platform/image.c. */",
          "SECTIONS {", *init, *data, "}", "INSERT AFTER .data;", "SECTIONS {", *bss, "}", "INSERT AFTER .bss;"]
    (out / "sections.ld").write_text("\n".join(ld) + "\n")

    h = ["/* Generated by tools/modgen.py. */", "#pragma once", "#include <stdint.h>",
         "typedef struct PortModule {",
         "    const char *name;",
         "    int overlay_id; /* -1: main, ITCM, DTCM */",
         "    const uint32_t *relocs; /* count, then (place, native address, DS address) triples (tools/gapgen.py) */",
         "    uint8_t *data_start, *data_end, *bss_start, *bss_end;",
         "    void (**init_start)(void), (**init_end)(void);",
         "} PortModule;",
         f"#define PORT_MODULE_COUNT {len(mods)}",
         "#define PORT_ARM9_MODULE_PARAMS 0x02004ad8u /* _start_ModuleParams (BuildInfo) */",
         "extern const PortModule g_port_modules[PORT_MODULE_COUNT];"]
    (out / "modules.h").write_text("\n".join(h) + "\n")
    c = ["/* Generated by tools/modgen.py. */", '#include "modules.h"']
    for m in mods:
        c.append(f"extern const uint32_t port_gap_relocs_{m}[];")
        c.append(f"extern uint8_t __port_{m}_data_start[], __port_{m}_data_end[], __port_{m}_bss_start[], "
                 f"__port_{m}_bss_end[];")
        c.append(f"extern void (*__port_{m}_init_start[])(void), (*__port_{m}_init_end[])(void);")
    c.append("const PortModule g_port_modules[PORT_MODULE_COUNT] = {")
    for m in mods:
        ov = int(m[2:]) if m.startswith("ov") else -1
        c.append(f'    {{"{m}", {ov}, port_gap_relocs_{m}, __port_{m}_data_start, __port_{m}_data_end, '
                 f"__port_{m}_bss_start, __port_{m}_bss_end, __port_{m}_init_start, __port_{m}_init_end}},")
    c.append("};")
    (out / "modules.c").write_text("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
