#!/usr/bin/env python3
"""Build the guest image of the arm64 port: the game and the DS platform layer compiled for AArch64 with 32-bit
pointers (GCC -mabi=ilp32) and linked at a fixed address below 4 GiB (port/guest/guest.ld).

Writes OUT/build.ninja and runs ninja, so rebuilds are incremental. The result is OUT/guest.elf.

Usage: build_guest.py <gen dir from portify> <out dir> [cross prefix, default aarch64-linux-gnu-]
"""
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORT = ROOT / "port"
PLATFORM_GUEST = ["os.c", "mi.c", "card.c", "overlay.c", "services.c", "wireless.c", "wm7.c", "asm_replacements.c", "hw.c",
                  "gx3d.c", "frame.c", "sound.c", "libc.c"]


def main():
    gen, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    cross = sys.argv[3] if len(sys.argv) > 3 else "aarch64-linux-gnu-"
    out.mkdir(parents=True, exist_ok=True)
    gcc_include = subprocess.check_output([cross + "gcc", "-print-file-name=include"], text=True).strip()

    overlay_of = {}
    for line in (gen / "overlay_units.txt").read_text().splitlines():
        ov, rel = line.split(" ", 1)
        overlay_of[rel] = ov

    # Imports: one jump through the import table per host function.
    abi = (PORT / "guest" / "guest_abi.h").read_text()
    imports = re.findall(r"X\((\w+)\)", abi[abi.index("#define HOST_IMPORTS"):])
    stubs = ["// Generated by tools/build_guest.py from HOST_IMPORTS (port/guest/guest_abi.h).", ".text"]
    for i, name in enumerate(imports):
        stubs += [f".globl {name}", f".type {name}, %function", f"{name}:",
                  "  adrp x16, g_host_imports", "  add x16, x16, :lo12:g_host_imports",
                  f"  ldr x16, [x16, #{8 * i}]", "  br x16"]
    imports_s = out / "imports.S"
    text = "\n".join(stubs) + "\n"
    if not imports_s.exists() or imports_s.read_text() != text:
        imports_s.write_text(text)

    common = ["-mabi=ilp32", "-O2", "-ffixed-x18", "-fno-pic", "-fno-pie", "-mno-outline-atomics", "-fno-stack-protector",
              "-fno-asynchronous-unwind-tables", "-fno-unwind-tables", "-ffreestanding", "-nostdinc",
              "-isystem", gcc_include, "-std=gnu11", "-fno-strict-aliasing", "-fwrapv", "-fcommon",
              "-Dversion_EUR", "-DGUEST_IMAGE=1"]
    includes = ["-I", str(gen / "include"), "-I", str(PORT / "platform" / "include"), "-I", str(PORT / "platform"),
                "-I", str(PORT / "guest")]
    # The game's own C library headers come first for its code; the guest's minimal ones for the platform layer.
    # The game's data must keep the original layout: some tables run on into the next definition (an array declared
    # with one element read further). GCC keeps definition order with -fno-toplevel-reorder, natural alignment of
    # arrays only when optimising for size (otherwise AArch64 aligns them to 8 or 16), and zero data next to the rest
    # with -fno-zero-initialized-in-bss.
    game_flags = [f if f != "-O2" else "-Os" for f in common] + ["-I", str(gen / "msl_include")] + includes + [
        "-I", str(PORT / "guest" / "include"), "-include", str(PORT / "compat" / "port_prefix.h"),
        "-fshort-wchar", "-Dconst=", "-fno-toplevel-reorder", "-fno-zero-initialized-in-bss", "-w"]
    platform_flags = common + ["-I", str(PORT / "guest" / "include")] + includes + ["-Wall", "-Wno-unused-function"]

    lines = [
        f"cc = {cross}gcc",
        f"ld = {cross}ld",
        "rule cc",
        "  command = $cc $flags -MD -MF $out.d -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = guest $in",
        "rule link",
        f"  command = $ld -m aarch64linux32 -static -nostdlib -T {PORT / 'guest' / 'guest.ld'} -o $out @$out.rsp",
        "  rspfile = $out.rsp",
        "  rspfile_content = $in",
        "  description = link guest",
    ]
    objects = []

    def add(src, obj, flags):
        lines.append(f"build {obj}: cc {src}")
        lines.append(f"  flags = {' '.join(flags)}")
        objects.append(str(obj))

    for src in (gen / "sources.txt").read_text().split():
        src = Path(src)
        rel = src.relative_to(gen / "src").as_posix()
        sign = ["-fsigned-char"] if rel.startswith("libs/") else ["-funsigned-char"]
        group = overlay_of.get(rel, "main")
        add(src, out / "obj" / group / (rel + ".o"), game_flags + sign)
    for name in PLATFORM_GUEST:
        add(PORT / "platform" / name, out / "obj" / "platform" / (name + ".o"), platform_flags + ["-fsigned-char"])
    for name in ["entry.c", "libc.c", "libc2.c"]:
        add(PORT / "guest" / name, out / "obj" / "guest" / (name + ".o"), platform_flags + ["-fsigned-char"])
    add(imports_s, out / "obj" / "guest" / "imports.S.o", ["-mabi=ilp32"])
    lines.append(f"build {out / 'guest.elf'}: link {' '.join(objects)} | {PORT / 'guest' / 'guest.ld'}")
    text = "\n".join(lines) + "\n"
    ninja_file = out / "build.ninja"
    if not ninja_file.exists() or ninja_file.read_text() != text:
        ninja_file.write_text(text)
    subprocess.check_call(["ninja", "-C", str(out)] + (["-v"] if os.environ.get("VERBOSE") else []))


if __name__ == "__main__":
    main()
